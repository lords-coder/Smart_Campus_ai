/**
 * Dark theme layer generator.
 *
 * The shell integration makes the prototype's dark palette the application's
 * palette. Two things have to happen for the fifteen already-verified phases to
 * follow it without being rewritten:
 *
 *   1. The shadcn semantic tokens (`--background`, `--card`, `--primary`, ...)
 *      are re-pointed at the prototype palette. Every `bg-card`,
 *      `text-muted-foreground`, `border-border` utility in the app resolves
 *      through those tokens, so the whole surface flips in one place.
 *
 *   2. The light end of the Tailwind palette is re-mapped, because roughly two
 *      hundred `bg-gray-100` / `text-red-800` / `border-green-300` utilities
 *      are written directly into the phase components. Rather than edit forty
 *      files, the shades actually in use are re-declared: light shades become
 *      dark tinted surfaces, dark shades become light tinted text, and any
 *      shade used as a background at 400+ is left alone so solid brand blocks
 *      keep their contrast.
 *
 * This file is generated by scripts/build-dark-theme.mjs - edit the script.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = path.resolve(ROOT, "src", "styles", "theme-dark.css");
const THEME = path.resolve(ROOT, "node_modules", "tailwindcss", "theme.css");
const SRC = path.resolve(ROOT, "src");

/** Every source file the utility scan looks at. */
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.tsx?$/.test(entry)) out.push(full);
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * 1. Read the prototype palette out of Tailwind's own default theme so
 *    the re-mapped shades keep each family's real hue and chroma.
 * ------------------------------------------------------------------ */
const themeCss = readFileSync(THEME, "utf8");
const palette = new Map(); // `${family}-${shade}` -> { l, c, h }
for (const match of themeCss.matchAll(/--color-([a-z]+)-(\d{2,3}):\s*oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*\)/g)) {
  palette.set(`${match[1]}-${match[2]}`, { l: Number(match[3]), c: Number(match[4]), h: Number(match[5]) });
}

/* ------------------------------------------------------------------ *
 * 2. Scan the app for direct palette utilities.
 * ------------------------------------------------------------------ */
const UTILITY = /\b(text|bg|border|ring|from|to|via|fill|stroke|outline|decoration|shadow|accent|caret|divide)-([a-z]+)-(\d{2,3})\b/g;
const usage = new Map(); // `${family}-${shade}` -> Set(prefix)

for (const file of walk(SRC)) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(UTILITY)) {
    const [, prefix, family, shade] = match;
    if (!palette.has(`${family}-${shade}`)) continue;
    if (prefix === "shadow") continue; // shadow-<family>-<n> is a size, not a colour
    const key = `${family}-${shade}`;
    if (!usage.has(key)) usage.set(key, new Set());
    usage.get(key).add(prefix);
  }
}

/* ------------------------------------------------------------------ *
 * 3. The mapping.
 * ------------------------------------------------------------------ */
const SURFACE_PREFIXES = new Set(["bg", "border", "ring", "from", "to", "via", "fill", "stroke", "outline", "decoration", "divide"]);

/** Tailwind shade numbers sort naturally as integers: 50 < 100 < 900. */
const shadeNumber = (shade) => Number(shade);

/**
 * On a light theme the low shades are the pale ones, so a `-100` is a surface
 * and a `-800` is body text. On a dark surface that inverts: `-50`..`-300`
 * become the light tints (used as text) and the dark tints (used as surfaces),
 * while `-400`..`-900` run light-to-lighter as text and stay untouched as solid
 * fills. The prefix decides which way a shade moves, not the shade number.
 */
const DARK_TINT = {
  50: { l: 19, c: 0.3 },
  100: { l: 23.5, c: 0.4 },
  200: { l: 30, c: 0.5 },
  300: { l: 39, c: 0.62 },
};
const LIGHT_TINT = {
  50: { l: 97, c: 0.1 },
  100: { l: 94, c: 0.14 },
  200: { l: 90, c: 0.2 },
  300: { l: 85, c: 0.28 },
  400: { l: 78, c: 0.6 },
  500: { l: 82, c: 0.5 },
  600: { l: 85, c: 0.42 },
  700: { l: 88, c: 0.35 },
  800: { l: 91, c: 0.28 },
  900: { l: 94, c: 0.22 },
};

/**
 * Shades that appear as both a surface and text cannot follow one rule, so the
 * winner is declared here rather than guessed. Each entry corresponds to a
 * source line that was converted to the neighbouring shade or to a semantic
 * token, so nothing depends on the exception.
 */
const BOTH_ROLES = {
  // Read as badge text ("bg-blue-100 text-blue-700") in six components; the one
  // solid fill that used it now uses bg-primary like every other primary button.
  "blue-600": "text",
  "blue-700": "text",
  // A badge border in six components; the one text use (the public certificate
  // verification page) now uses text-amber-400.
  "amber-300": "surface",
};

const overrides = [];
const skipped = [];
const both = [];

for (const [key, prefixes] of [...usage.entries()].sort()) {
  const [family, shade] = [key.slice(0, key.lastIndexOf("-")), key.slice(key.lastIndexOf("-") + 1)];
  const base = palette.get(key);
  const n = shadeNumber(shade);
  const usedAsSurface = [...prefixes].some((p) => SURFACE_PREFIXES.has(p));
  const usedAsText = prefixes.has("text");

  let role = usedAsSurface ? "surface" : "text";
  if (usedAsSurface && usedAsText) {
    both.push(`${family}-${shade}`);
    role = BOTH_ROLES[key];
    if (!role) throw new Error(`${key} is used as both text and surface; declare it in BOTH_ROLES`);
  }

  // A shade painted only as a solid background at 400+ is a brand block;
  // lightening it would destroy its contrast with the text on top.
  if (role === "surface" && !(n in DARK_TINT)) {
    skipped.push(`${family}-${shade} (solid surface)`);
    continue;
  }

  const target = role === "surface" ? DARK_TINT[n] : LIGHT_TINT[n];
  if (!target) {
    skipped.push(`${family}-${shade} (unmapped shade)`);
    continue;
  }

  // The neutral families (gray, slate, ...) carry almost no chroma, so scaling it
  // would leave pure-gray panels and text sitting inside the prototype's navy
  // surfaces. A floor keeps them in the same hue family as the shell.
  const neutral = base.c < 0.02;
  const floor = role === "surface" ? 0.012 : 0.008;
  const c = Number(Math.max(base.c * target.c, neutral ? floor : 0).toFixed(4));
  overrides.push({
    name: `--color-${family}-${shade}`,
    value: `oklch(${target.l}% ${c} ${base.h})`,
    role,
  });
}

/* ------------------------------------------------------------------ *
 * 4. Emit.
 * ------------------------------------------------------------------ */
// The prototype palette, from C:\test\tt\frontend\app\globals.css `:root`.
const TOKENS = {
  background: "#070f1b",
  foreground: "#f0f6fb",
  card: "#101f32",
  "card-foreground": "#f0f6fb",
  popover: "#14273c",
  "popover-foreground": "#f0f6fb",
  primary: "#37d7d1",
  "primary-foreground": "#05161c",
  secondary: "#0e1b2a",
  "secondary-foreground": "#a4b6c8",
  muted: "#0e1b2a",
  "muted-foreground": "#a4b6c8",
  accent: "#16283c",
  "accent-foreground": "#e8f1f8",
  destructive: "#e5484d",
  border: "rgba(158, 188, 214, 0.14)",
  input: "rgba(158, 188, 214, 0.2)",
  ring: "rgba(77, 230, 221, 0.55)",
  "chart-1": "#37d7d1",
  "chart-2": "#79b7ff",
  "chart-3": "#ac9aff",
  "chart-4": "#ffbe5c",
  "chart-5": "#7ee787",
  radius: "0.75rem",
  sidebar: "#0b1726",
  "sidebar-foreground": "#f0f6fb",
  "sidebar-primary": "#37d7d1",
  "sidebar-primary-foreground": "#05161c",
  "sidebar-accent": "#16283c",
  "sidebar-accent-foreground": "#e8f1f8",
  "sidebar-border": "rgba(158, 188, 214, 0.14)",
  "sidebar-ring": "rgba(77, 230, 221, 0.55)",
};

const semantic = Object.entries(TOKENS)
  .map(([token, value]) => `  --${token}: ${value};`)
  .join("\n");

const surfaceOverrides = overrides.filter((o) => o.role === "surface");
const textOverrides = overrides.filter((o) => o.role === "text");

const css = `/**
 * Global dark theme.
 *
 * Generated by scripts/build-dark-theme.mjs - edit the script, not this file.
 *
 * The prototype's dark palette is now the application's palette. These are the
 * shadcn semantic tokens every existing component already reads through
 * (bg-card, text-muted-foreground, border-border, bg-primary, ...), so all
 * fifteen phases follow the shell without being rewritten.
 *
 * The second block re-maps the shades of Tailwind's own palette that the phase
 * components reference directly, so no light pill, panel or border survives the
 * switch to a dark shell. Shades used as a solid background at 400+ are left
 * untouched: see the script for the rule and the skipped list.
 */

:root {
  color-scheme: dark;

  /* Surfaces, from the prototype's own surfaces. */
${semantic}

  /* Light shades used as surfaces or borders -> dark tinted equivalents. */
${surfaceOverrides.map((o) => `  ${o.name}: ${o.value};`).join("\n")}

  /* Dark shades used as text -> light tinted equivalents. */
${textOverrides.map((o) => `  ${o.name}: ${o.value};`).join("\n")}
}
`;

mkdirSync(path.dirname(TARGET), { recursive: true });
writeFileSync(TARGET, css, "utf8");

// Verification.
const written = readFileSync(TARGET, "utf8");
if (!written.includes("--background: #070f1b")) throw new Error("semantic tokens missing");
if (skipped.length) {
  console.log("left at Tailwind's default (solid surfaces):");
  for (const entry of skipped) console.log(`  ${entry}`);
}
if (both.length) {
  console.log("used as both text and surface (BOTH_ROLES decides):");
  for (const entry of both) console.log(`  ${entry} -> ${BOTH_ROLES[entry]}`);
}
console.log(`wrote    ${path.relative(ROOT, TARGET)}`);
console.log(`bytes    ${written.length}`);
console.log(`tokens   ${Object.keys(TOKENS).length} semantic`);
console.log(`palette  ${overrides.length} shades re-mapped (${surfaceOverrides.length} surface, ${textOverrides.length} text) of ${usage.size} used`);
console.log(`left     ${skipped.length}`);
